// Converts one matchday of Fantacalcio.it votes (Voti_Fantacalcio_Stagione_*_Giornata_N.xlsx,
// the "Voti" download of the matchday page) into the JSON the site imports, and refreshes the
// index of the rounds available. One row per player:
//   [team, role, name, voto, gf, gs, rp, rs, rf, au, amm, esp, ass]
// voto is null when the player had no vote (s.v.). The workbook lists each club as a block:
// a row with the club's name, a header row (Cod. Ruolo Nome Voto Gf Gs Rp Rs Rf Au Amm Esp Ass),
// then the players. Columns are found by their header, so their order does not matter.
// Usage: node scripts/fantacalcio-voti-to-json.mjs <votes.xlsx> <round> [league=serie-a]
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {readWorkbook} from './xlsx.mjs';

const [, , input, roundArg, leagueArg] = process.argv;
const round = Number(roundArg);
const league = leagueArg ?? 'serie-a';
if (!input || !Number.isInteger(round) || round < 1) {
    console.error('usage: node scripts/fantacalcio-voti-to-json.mjs <votes.xlsx> <round> [league]');
    process.exit(1);
}
const {sheets, rows} = readWorkbook(readFileSync(input));
const text = (v) => (v === null || v === undefined ? '' : String(v).trim());
const num = (v) => {
    const n = Number(String(v ?? '').replace(',', '.'));
    return Number.isFinite(n) ? n : 0;
};
/** "6", "6,5", "6*" (no vote) -> the vote or null. */
const voto = (v) => {
    const s = text(v);
    if (!s || /\*/.test(s) || /^s\.?v\.?$/i.test(s)) return null;
    const n = Number(s.replace(',', '.'));
    return Number.isFinite(n) && n >= 1 && n <= 10 ? n : null;
};
const COLUMNS = {cod: /^cod/i, role: /^r(uolo)?$/i, name: /^nome/i, voto: /^voto/i, gf: /^gf$/i, gs: /^gs$/i, rp: /^rp$/i, rs: /^rs$/i, rf: /^rf$/i, au: /^au$/i, amm: /^amm/i, esp: /^esp/i, ass: /^ass/i};

const out = [];
let team = '';
let at = null;
for (const sheet of sheets) {
    for (const r of rows(sheet)) {
        const cells = r.map(text);
        const filled = cells.filter((c) => c !== '');
        if (filled.length === 0) continue;
        // A header row names the columns; the block's club is the last lone text before it.
        if (cells.some((c) => COLUMNS.name.test(c)) && cells.some((c) => COLUMNS.voto.test(c))) {
            at = {};
            cells.forEach((c, i) => {
                for (const [key, re] of Object.entries(COLUMNS)) if (re.test(c) && at[key] === undefined) at[key] = i;
            });
            continue;
        }
        if (filled.length === 1 && !/^\d+$/.test(filled[0]) && !/^voti/i.test(filled[0])) {
            team = filled[0];
            continue;
        }
        if (!at || at.name === undefined) continue;
        const code = cells[at.cod ?? -1] ?? '';
        const name = cells[at.name];
        const role = (cells[at.role ?? -1] ?? '').toUpperCase();
        if (!name || !/^[PDCA]$/.test(role) || (at.cod !== undefined && !/^\d+$/.test(code))) continue;
        out.push([team, role, name, voto(cells[at.voto]), num(cells[at.gf]), num(cells[at.gs]), num(cells[at.rp]), num(cells[at.rs]), num(cells[at.rf]), num(cells[at.au]), num(cells[at.amm]), num(cells[at.esp]), num(cells[at.ass])]);
    }
}
if (out.length === 0) {
    console.error('no votes found: is this the Fantacalcio.it "Voti" workbook?');
    process.exit(1);
}
const dir = `core/fantasy/voti/${league}`;
writeFileSync(`${dir}/${round}.json`, `${JSON.stringify(out)}\n`);
// The index: every round on disk, imported statically so the site bundles them.
const available = readdirSync(dir).map((f) => /^(\d+)\.json$/.exec(f)?.[1]).filter(Boolean).map(Number).sort((a, b) => a - b);
const index = [
    '// Generated by scripts/fantacalcio-voti-to-json.mjs: the official votes of every round on disk.',
    "import type {VotoRow} from '@/lib/fantasy/voti';",
    ...available.map((n) => `import r${n} from './${n}.json';`),
    '',
    'export const VOTI: Array<{round: number; rows: VotoRow[]}> = [',
    ...available.map((n) => `    {round: ${n}, rows: r${n} as VotoRow[]},`),
    '];',
    '',
];
writeFileSync(`${dir}/index.ts`, index.join('\n'));
console.log(`${out.length} votes (${out.filter((r) => r[3] === null).length} without a vote), ${new Set(out.map((r) => r[0])).size} clubs -> ${dir}/${round}.json; index: rounds ${available.join(', ')}`);
